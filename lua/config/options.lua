local opt = vim.opt

-- Line numbers
opt.number = true
opt.relativenumber = true

-- Indentation
opt.tabstop = 4
opt.shiftwidth = 4
opt.softtabstop = -1
opt.expandtab = true

-- Search
opt.ignorecase = true
opt.smartcase = true

-- Editor
opt.wrap = false
opt.cursorline = true
opt.scrolloff = 8
opt.signcolumn = "yes"

-- Clipboard
opt.clipboard = "unnamedplus"

-- Appearance
opt.termguicolors = true

-- Windows
opt.splitright = true
opt.splitbelow = true
